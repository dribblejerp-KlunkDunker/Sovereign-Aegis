/**
 * SOVEREIGN // AEGIS — inline-style extractor (CSP hardening, ROADMAP §8)
 *
 * Moves every static `style="…"` attribute in index.html into css/extracted-inline.css,
 * so the CSP's `style-src 'unsafe-inline'` can eventually be dropped. (It cannot be
 * dropped yet: the JS view templates still emit inline styles — see STATUS.md item 5.)
 *
 *     node tools/extract-inline-styles.mjs           # rewrite index.html + regenerate css
 *     node tools/extract-inline-styles.mjs --check   # exit 1 if index.html has style=""
 *
 * HOW IT PRESERVES BEHAVIOR
 * -------------------------
 * - Each element gets `data-ix="<hash>"`, not a class. Several modules overwrite
 *   `el.className` wholesale; a class would be wiped where an inline style survived.
 *   Nothing in js/ touches data-ix.
 * - Identical declaration blocks share one hash; declaration text and order are kept
 *   verbatim, so a repeated property still resolves the same way.
 * - Inline styles beat every non-!important stylesheet rule regardless of specificity.
 *   An attribute selector alone would not, so each rule is written as
 *       :is([data-ix="h"], #ix-never#ix-never) { … }
 *   :is() takes the specificity of its most specific argument — (2,0,0) here — and the
 *   never-matching double-ID argument adds no matches. No existing selector uses more
 *   than one ID, so these rules win exactly where the inline style used to. !important
 *   stylesheet rules still win, as they did over inline styles. JS writes through
 *   `el.style.*` are inline and still override these rules, as before.
 * - Safe only because no JS reads an index.html element's inline value back
 *   (`el.style.x === …`) or resets it with `el.style.x = ''` — verified when this ran
 *   (2026-11-06). If such code is added, the value must live in a class it toggles.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HTML = path.join(ROOT, 'index.html');
const CSS = path.join(ROOT, 'css', 'extracted-inline.css');
const LINK = '<link rel="stylesheet" href="css/extracted-inline.css">';

const html = fs.readFileSync(HTML, 'utf8');
const STYLE_ATTR = /\sstyle="([^"]*)"/g;
// HTML comments may mention style="" in prose (the CSP note does); they are not markup.
const withoutComments = (s) => s.replace(/<!--[\s\S]*?-->/g, '');
const countInlineStyles = (s) => [...withoutComments(s).matchAll(STYLE_ATTR)].length;

if (process.argv.includes('--check')) {
  const n = countInlineStyles(html);
  console.log(n ? `index.html still has ${n} style="" attribute(s)` : 'index.html: 0 style="" attributes');
  process.exit(n ? 1 : 0);
}

const normalize = (decl) =>
  decl.split(';').map((d) => d.trim().replace(/\s+/g, ' ')).filter(Boolean).join('; ');

// Existing rules are kept, so re-running after a few new inline styles appear only appends.
const rules = new Map(); // hash -> normalized declarations
if (fs.existsSync(CSS)) {
  for (const m of fs.readFileSync(CSS, 'utf8').matchAll(/\[data-ix="([0-9a-f]+)"\][^{]*\{\s*([^}]*?)\s*\}/g)) {
    rules.set(m[1], normalize(m[2]));
  }
}

let converted = 0;
let skipped = 0;
// Walk tag-by-tag so a style attribute is only ever rewritten inside its own start tag.
const out = html.replace(/<!--[\s\S]*?-->|<([a-zA-Z][a-zA-Z0-9-]*)\b([^<>]*?)(\/?)>/g, (tag, name, attrs, selfClose) => {
  if (name === undefined) return tag; // a comment: leave it byte-for-byte
  const m = /\sstyle="([^"]*)"/.exec(attrs);
  if (!m) return tag;
  if (/\sdata-ix=/.test(attrs)) { skipped++; return tag; } // never double-tag
  const decl = normalize(m[1]);
  if (!decl) { converted++; return `<${name}${attrs.replace(m[0], '')}${selfClose}>`; }
  const hash = crypto.createHash('sha1').update(decl).digest('hex').slice(0, 7);
  const prior = rules.get(hash);
  if (prior !== undefined && prior !== decl) throw new Error(`hash collision on ${hash}`);
  rules.set(hash, decl);
  converted++;
  return `<${name}${attrs.replace(m[0], ` data-ix="${hash}"`)}${selfClose}>`;
});

const remaining = countInlineStyles(out);
if (remaining) throw new Error(`${remaining} style="" attribute(s) were not inside a parseable start tag`);

let finalHtml = out;
if (!finalHtml.includes(LINK)) {
  const anchor = '<link rel="stylesheet" href="css/animations.css">';
  if (!finalHtml.includes(anchor)) throw new Error('could not find the animations.css <link> to insert after');
  finalHtml = finalHtml.replace(anchor, `${anchor}\n  ${LINK}`);
}

const body = [...rules.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([h, d]) => `:is([data-ix="${h}"], #ix-never#ix-never) { ${d} }`)
  .join('\n');
fs.writeFileSync(CSS, `/*
 * GENERATED by tools/extract-inline-styles.mjs from index.html's former style="" attributes.
 * Each rule styles the elements carrying the matching data-ix hash. The :is(…, #ix-never#ix-never)
 * wrapper gives these rules (2,0,0) specificity so they win wherever the inline style used to —
 * see the tool's header before changing that. Editing a rule here restyles every element that
 * shares its hash; to restyle one element, give it its own class instead.
 */
${body}
`);
fs.writeFileSync(HTML, finalHtml);
console.log(`converted ${converted} style="" attribute(s) into ${rules.size} rule(s); skipped ${skipped}; ${remaining} left`);
